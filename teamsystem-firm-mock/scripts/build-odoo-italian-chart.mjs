// scripts/build-odoo-italian-chart.mjs — turns Odoo's real Italian chart of
// accounts (odoo/odoo addons/l10n_it/data/template/account.account-it.csv,
// LGPL-3, copied into sample-documents/reference/odoo-l10n-it/) into the
// chart-of-accounts shape this mock serves: { code, name, type, rate, natura }.
//
// Odoo's CSV has no account -> VAT rate column (its tax model lives on the
// transaction, not the account), so the rate/natura below is a judgment call
// per account, made the same way the 10 hand-built clients were:
//   - goods & services bought/sold normally            -> 22%
//   - insurance, postal, bank fees, interest, rent     -> 0% + N4 (art. 10 DPR 633/1972)
//   - balance-sheet, payroll, depreciation, provisions,
//     taxes, inventory movements, closing accounts     -> rate null (no invoices
//     land there, so CST-04 has nothing to check)
//
// Run: node scripts/build-odoo-italian-chart.mjs  (rewrites backend/data/odooItalianChart.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const csv = readFileSync(`${root}sample-documents/reference/odoo-l10n-it/account.account-it.csv`, "utf8");

function parseCsvLine(line) {
  const out = []; let cur = ""; let q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const [header, ...rows] = csv.trim().split(/\r?\n/).map(parseCsvLine);
const col = (name) => header.indexOf(name);

const STANDARD_22 = new Set([
  // purchases of goods (incl. returns/discounts, which carry the same rate)
  "4101", "4102", "4105", "4110", "4111", "4112",
  // services
  "4201", "4202", "4203", "4204", "4206", "4208", "4209", "4210", "4211", "4212",
  "4302", // leasing
  // sales
  "3101", "3103", "3110", "3111", "3112", "3202",
]);
const EXEMPT_N4 = new Set([
  "4205", // postal (art. 10 n. 16)
  "4207", // insurance (art. 10 n. 2)
  "4213", // collection/bank fees (art. 10 n. 1)
  "4301", "3201", // property rent, passive/active (art. 10 n. 8)
  "5201", "5202", "5203", "5210", "5240", // interest & financial charges (art. 10 n. 1)
  "5110", "5115", "5116", "5140",
]);

const chart = rows.map((r) => {
  const code = r[col("code")];
  const vat = STANDARD_22.has(code) ? { rate: 22, natura: null }
    : EXEMPT_N4.has(code) ? { rate: 0, natura: "N4" }
    : { rate: null, natura: null };
  return { code, name: r[col("name@it")] || r[col("name")], type: r[col("account_type")], ...vat };
});

const body = chart.map((c) => `  { ${Object.entries(c).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(", ")} },`).join("\n");
writeFileSync(`${root}backend/data/odooItalianChart.mjs`,
`// backend/data/odooItalianChart.mjs — GENERATED by scripts/build-odoo-italian-chart.mjs
// from Odoo's real Italian chart of accounts (odoo/odoo addons/l10n_it, LGPL-3).
// Codes, Italian names and account types are Odoo's; rate/natura are this
// project's per-account assignments (see the script header). Don't hand-edit.

export const odooItalianChart = [
${body}
];
`);
console.log(`wrote ${chart.length} accounts (${chart.filter((c) => c.rate === 22).length} at 22%, ${chart.filter((c) => c.natura === "N4").length} N4, ${chart.filter((c) => c.rate === null).length} unrated)`);
